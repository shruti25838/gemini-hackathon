"""Generate JSON Schema from the Pydantic contracts, and TypeScript from that.

  python scripts/gen_schemas.py          write contracts/schemas/ and web/src/types/
  python scripts/gen_schemas.py --check  fail if anything on disk is out of date

contracts/schemas/ and web/src/types/ are generated, never hand-edited. The
contract test and CI both run --check, so a model change that is not
regenerated fails the build instead of drifting away from the frontend.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from contracts import CONTRACT_MODELS  # noqa: E402

SCHEMA_DIR = REPO_ROOT / "contracts" / "schemas"
TS_DIR = REPO_ROOT / "web" / "src" / "types"

HEADER = "// Generated by scripts/gen_schemas.py. Do not edit by hand.\n"


def snake(name: str) -> str:
    """RoomSpec -> room_spec"""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


# --------------------------------------------------------------------------
# JSON Schema
# --------------------------------------------------------------------------


def build_schemas() -> dict[str, dict[str, Any]]:
    """One JSON Schema document per contract, serialised deterministically."""
    out: dict[str, dict[str, Any]] = {}
    for name, model in CONTRACT_MODELS.items():
        schema = model.model_json_schema(mode="serialization")
        schema["title"] = name
        out[f"{snake(name)}.schema.json"] = schema
    return out


def dump_json(schema: dict[str, Any]) -> str:
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"


# --------------------------------------------------------------------------
# TypeScript
# --------------------------------------------------------------------------


def ts_name(ref: str) -> str:
    """'#/$defs/Money' -> 'Money'"""
    return ref.rsplit("/", 1)[-1]


def ts_type(node: dict[str, Any]) -> str:
    """Render one JSON Schema node as a TypeScript type expression."""
    if "$ref" in node:
        return ts_name(node["$ref"])

    if "const" in node:
        return json.dumps(node["const"])

    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])

    for key in ("anyOf", "oneOf"):
        if key in node:
            parts = [ts_type(sub) for sub in node[key]]
            # Collapse the pydantic Optional[...] pattern into "T | null".
            seen: list[str] = []
            for part in parts:
                if part not in seen:
                    seen.append(part)
            return " | ".join(seen)

    if "allOf" in node and len(node["allOf"]) == 1:
        return ts_type(node["allOf"][0])

    node_type = node.get("type")

    if node_type == "array":
        items = node.get("items")
        if not items:
            return "unknown[]"
        inner = ts_type(items)
        return f"({inner})[]" if " " in inner else f"{inner}[]"

    if node_type == "object":
        extra = node.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"

    if node_type == "string":
        return "string"
    if node_type in ("integer", "number"):
        return "number"
    if node_type == "boolean":
        return "boolean"
    if node_type == "null":
        return "null"

    if isinstance(node_type, list):
        return " | ".join(ts_type({"type": t}) for t in node_type)

    return "unknown"


def render_interface(name: str, node: dict[str, Any]) -> str:
    """One object schema as a TypeScript interface, or a type alias when the
    schema is an enum rather than an object."""
    if "enum" in node and "properties" not in node:
        return f"export type {name} = {ts_type(node)};\n"

    lines: list[str] = []
    description = node.get("description")
    if description:
        lines.append(f"/** {' '.join(description.split())} */")
    lines.append(f"export interface {name} {{")

    required = set(node.get("required", []))
    for prop, sub in node.get("properties", {}).items():
        prop_doc = sub.get("description")
        if prop_doc:
            lines.append(f"  /** {' '.join(prop_doc.split())} */")
        optional = "" if prop in required else "?"
        lines.append(f"  {prop}{optional}: {ts_type(sub)};")

    lines.append("}")
    return "\n".join(lines) + "\n"


def build_typescript(schemas: dict[str, dict[str, Any]]) -> str:
    """One module holding every contract type, so imports stay simple."""
    chunks: list[str] = [HEADER, "\n"]
    emitted: set[str] = set()

    # $defs first, in a stable order, then the twelve root contracts.
    defs: dict[str, dict[str, Any]] = {}
    for schema in schemas.values():
        for def_name, def_node in schema.get("$defs", {}).items():
            defs.setdefault(def_name, def_node)

    for def_name in sorted(defs):
        chunks.append(render_interface(def_name, defs[def_name]))
        chunks.append("\n")
        emitted.add(def_name)

    for filename in sorted(schemas):
        schema = schemas[filename]
        name = schema["title"]
        if name in emitted:
            continue
        chunks.append(render_interface(name, schema))
        chunks.append("\n")
        emitted.add(name)

    contract_names = sorted(s["title"] for s in schemas.values())
    chunks.append("/** Every root contract, for exhaustive switches. */\n")
    chunks.append(
        "export type ContractName =\n"
        + "\n".join(f"  | {json.dumps(n)}" for n in contract_names)
        + ";\n"
    )
    return "".join(chunks)


# --------------------------------------------------------------------------
# Entry point
# --------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write. Exit non-zero if anything on disk is out of date.",
    )
    args = parser.parse_args()

    schemas = build_schemas()
    typescript = build_typescript(schemas)

    targets: dict[Path, str] = {
        SCHEMA_DIR / filename: dump_json(schema) for filename, schema in schemas.items()
    }
    targets[TS_DIR / "contracts.ts"] = typescript

    if args.check:
        stale: list[str] = []
        for path, content in targets.items():
            rel = path.relative_to(REPO_ROOT)
            if not path.exists():
                stale.append(f"missing: {rel}")
            elif path.read_text(encoding="utf-8") != content:
                stale.append(f"out of date: {rel}")

        # An orphan schema means a contract was removed without regenerating.
        expected = {p.name for p in targets if p.parent == SCHEMA_DIR}
        if SCHEMA_DIR.exists():
            for path in SCHEMA_DIR.glob("*.schema.json"):
                if path.name not in expected:
                    stale.append(f"orphan: {path.relative_to(REPO_ROOT)}")

        if stale:
            print("Generated files are out of date. Run: python scripts/gen_schemas.py")
            for line in stale:
                print(f"  {line}")
            return 1
        print(f"Up to date: {len(targets)} generated files match the models.")
        return 0

    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    TS_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in targets.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
